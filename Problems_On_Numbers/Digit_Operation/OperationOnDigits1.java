public class OperationOnDigits1
{
    public static void main(String[] args)
    {
        int iNo = 12457;

        System.out.println(iNo % 10);
        iNo = iNo / 10;

        System.out.println(iNo % 10);
        iNo = iNo / 10;

        System.out.println(iNo % 10);
        iNo = iNo / 10;

        System.out.println(iNo % 10);
        iNo = iNo / 10;

        System.out.println(iNo % 10);
        iNo = iNo / 10;
    }
}